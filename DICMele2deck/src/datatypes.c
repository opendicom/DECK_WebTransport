u8 intdecsize(int i)
{
   //4294967295 negative ...11 char
   if (i<0)
   {
      if (i>-10000)
      {
         if (i>-100)
         {
            if (i>-10) return 2;
            return 3;
         }
         else
         {
            if (i>-1000) return 4;
            return 5;
         }
      }
      else
      {
         if (i>-100000000)
         {
            if (i>-1000000)
            {
               if (i>-100000) return 6;
               return 7;
            }
            else
            {
               if (i>-10000000) return 8;
               return 9;
            }
         }
         else
         {
            if (i>-1000000000) return 10;
            return 11;
         }
      }
   }
   else
   {
      if (i<10000)
      {
         if (i<100)
         {
            if (i<10) return 1;
            return 2;
         }
         else
         {
            if (i<1000) return 3;
            return 4;
         }
      }
      else
      {
         if (i<100000000)
         {
            if (i<1000000)
            {
               if (i<100000) return 5;
               return 6;
            }
            else
            {
               if (i<10000000) return 7;
               return 8;
            }
         }
         else
         {
            if (i<1000000000) return 9;
            return 10;
         }
      }
   }
}
u64 u64swap(u64 x)
{
   return ((x>>56) & 0xff)
         |((x>>40) & 0xff00)
         |((x>>24) & 0xff0000)
         |((x>>8)  & 0xff000000)
         |((x<<8)  & 0xff00000000)
         |((x<<24) & 0xff0000000000)
         |((x<<40) & 0xff000000000000)
         |((x<<56) & 0xff00000000000000);
}

u32 u32swap(u32 x)
{  //1234 -> 4321
   return ((x>>24) & 0xff)
         |((x>>8)  & 0xff00)
         |((x<<8)  & 0xff0000)
         |((x<<24) & 0xff000000);
}

u16 u16swap(u16 x)
{
   return ((x>>8) & 0xff)
         |((x<<8) & 0xff00);
}

u32 tagswap(u32 x)
{
   return ((x & 0xff       <<16))
         |((x & 0xff00    << 8))
         |((x & 0xff0000  >>16))
         |((x & 0xff000000 >>24));
}

